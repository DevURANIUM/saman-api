"""Generate explicit async methods from the synchronous client contract.

Run after changing client.py; commit the generated async_client.py.
The wheel does not need this tool or execute code generation during install.
"""

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


class Asyncify(ast.NodeTransformer):
    def visit_ImportFrom(self, node):
        if node.module == "_transport":
            for name in node.names:
                if name.name in {"send", "collect"}:
                    name.name = "async_" + name.name
        if node.module == "typing":
            node.names.append(ast.alias(name="Awaitable"))
            for name in node.names:
                if name.name == "Iterator":
                    name.name = "AsyncIterator"
        return node

    def visit_Subscript(self, node):
        self.generic_visit(node)
        if (
            isinstance(node.value, ast.Name)
            and node.value.id == "Callable"
            and isinstance(node.slice, ast.Tuple)
        ):
            node.slice.elts[1] = ast.BinOp(
                left=node.slice.elts[1],
                op=ast.BitOr(),
                right=ast.Subscript(
                    value=ast.Name(id="Awaitable", ctx=ast.Load()),
                    slice=ast.Name(id="str", ctx=ast.Load()),
                    ctx=ast.Load(),
                ),
            )
        return node

    def visit_ClassDef(self, node):
        node.name = "AsyncClient"
        methods = {n.name for n in node.body if isinstance(n, ast.FunctionDef)} - {
            "__init__",
            "__repr__",
        }
        self.methods = methods
        for index, item in enumerate(node.body):
            if isinstance(item, ast.FunctionDef):
                item = self.generic_visit(item)
                if item.name in methods:
                    item = ast.AsyncFunctionDef(
                        name={"__enter__": "__aenter__", "__exit__": "__aexit__"}.get(
                            item.name, item.name
                        ),
                        args=item.args,
                        body=item.body,
                        decorator_list=item.decorator_list,
                        returns=item.returns,
                        type_comment=item.type_comment,
                    )
                node.body[index] = item
        return node

    def visit_Name(self, node):
        if node.id == "Client":
            node.id = "AsyncClient"
        if node.id == "Iterator":
            node.id = "AsyncIterator"
        return node

    def visit_Attribute(self, node):
        self.generic_visit(node)
        if isinstance(node.value, ast.Name) and node.value.id == "httpx":
            node.attr = {
                "Client": "AsyncClient",
                "BaseTransport": "AsyncBaseTransport",
            }.get(node.attr, node.attr)
        return node

    def visit_Call(self, node):
        self.generic_visit(node)
        if isinstance(node.func, ast.Name) and node.func.id in {"send", "collect"}:
            node.func.id = "async_" + node.func.id
            return ast.Await(value=node)
        if isinstance(node.func, ast.Attribute):
            if (
                isinstance(node.func.value, ast.Name)
                and node.func.value.id == "self"
                and node.func.attr in getattr(self, "methods", set())
            ):
                return ast.Await(value=node)
            if (
                isinstance(node.func.value, ast.Attribute)
                and node.func.value.attr == "_http"
                and node.func.attr == "close"
            ):
                node.func.attr = "aclose"
                return ast.Await(value=node)
        return node

    def visit_Expr(self, node):
        if isinstance(node.value, ast.YieldFrom):
            return ast.For(
                target=ast.Name(id="row", ctx=ast.Store()),
                iter=node.value.value,
                body=[
                    ast.Expr(value=ast.Yield(value=ast.Name(id="row", ctx=ast.Load())))
                ],
                orelse=[],
            )
        return self.generic_visit(node)


source = ast.parse((ROOT / "src/saman_mobillet/client.py").read_text(encoding="utf8"))
tree = ast.fix_missing_locations(Asyncify().visit(source))
text = (
    "# Generated by tools/generate_async.py; do not edit by hand.\n"
    + ast.unparse(tree).replace("Synchronous client for", "Asynchronous client for")
    + "\n"
)
(ROOT / "src/saman_mobillet/async_client.py").write_text(text, encoding="utf8")
print("Generated async_client.py")
